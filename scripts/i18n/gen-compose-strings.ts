// Generates mobile/ui/build/generated/.../GeneratedStrings.kt from locales/*.json.
// One all-keys map (locale -> key -> ICU message) backing the Compose
// Multiplatform Localizer. Run: bun scripts/i18n/gen-compose-strings.ts
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'

import { kotlinString, supportedLocales } from './catalog'

const root = join(import.meta.dir, '..', '..')
const catalogDirectory = join(root, 'locales')
const out =
  process.argv[2] ??
  join(root, 'mobile/ui/build/generated/i18n/commonMain/kotlin/jp/nonbili/meron/ui/GeneratedStrings.kt')

// Canonical file code -> app BCP-47 tag (underscore -> hyphen for script/region).
const tagFor = (code: string): string => code.replace('_', '-')

const files = supportedLocales.map((code) => code + '.json')

// One function per locale keeps each JVM method well under the 64 KB bytecode
// limit (a single combined map initializer overflows it).
const functionName = (tag: string): string => 'locale_' + tag.replace(/[^A-Za-z0-9]/g, '_')

const mobileExcludedKeys = new Set([
  'mobile.accounts.oauthClientHint',
  'mobile.accounts.oauthClientId',
  'mobile.accounts.oauthClientSecretOptional',
])

let topEntries = ''
let functions = ''
for (const file of files) {
  const code = file.replace(/\.json$/, '')
  const tag = tagFor(code)
  const data = JSON.parse(readFileSync(join(catalogDirectory, file), 'utf8')) as Record<string, string>
  topEntries += `    "${tag}" to ${functionName(tag)}(),\n`
  functions += `private fun ${functionName(tag)}(): Map<String, String> =\n    buildMap {\n`
  for (const key of Object.keys(data).sort()) {
    if (mobileExcludedKeys.has(key)) continue
    functions += `        put(${kotlinString(key)}, ${kotlinString(data[key])})\n`
  }
  functions += `    }\n\n`
}

const kotlinSource = `// Generated by scripts/i18n/gen-compose-strings.ts. Do not edit by hand.
package jp.nonbili.meron.ui

internal val generatedStrings: Map<String, Map<String, String>> = mapOf(
${topEntries})

${functions}`

mkdirSync(dirname(out), { recursive: true })
writeFileSync(out, kotlinSource)
console.log(`Wrote ${out} (${files.length} locales)`)
